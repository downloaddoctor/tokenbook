/* Cross-origin assets cached best-effort. ONLY hosts without their own SW belong
   here — Dexie (unpkg) and Google Fonts. paperstamp (downloaddoctor.github.io)
   is deliberately excluded: it ships its own SW. Cache-first so the app still
   boots offline. */
const RUNTIME_HOSTS = new Set([
  'unpkg.com',
  'fonts.googleapis.com',
  'fonts.gstatic.com',
]);

/* ---------- Validator helpers ---------- */

function validatorOf(res) {
  if (!res || !res.ok) return null;
  return res.headers.get('ETag') || res.headers.get('Last-Modified') || null;
}

/* Sentinel fallback for servers that send no ETag/Last-Modified: GET the body
   and use its text as the validator (version.txt is a tiny timestamp file). */
async function sentinelBodyValidator() {
  try {
    const res = await fetch(SENTINEL_URL, { cache: 'no-store' });
    return res && res.ok ? 'body:' + (await res.text()).trim() : null;
  } catch (err) {
    return null;
  }
}

/* HEAD a URL and return its validator string (no body downloaded). */
async function headValidator(url) {
  try {
    const res = await fetch(url, { method: 'HEAD', cache: 'no-store' });
    return validatorOf(res);
  } catch (err) {
    return null;
  }
}

async function fetchSentinelValidator() {
  return (await headValidator(SENTINEL_URL)) || (await sentinelBodyValidator());
}

async function readStored(key) {
  try {
    const cache = await caches.open(META_CACHE);
    const res = await cache.match(key);
    return res ? await res.text() : null;
  } catch (err) {
    return null;
  }
}

async function writeStored(key, value) {
  const cache = await caches.open(META_CACHE);
  await cache.put(
    key,
    new Response(value || '', { headers: { 'Content-Type': 'text/plain' } })
  );
}

function readStoredValidator() {
  return readStored(SENTINEL_KEY);
}

function writeStoredValidator(value) {
  return writeStored(SENTINEL_KEY, value);
}

function readLastCheck() {
  return readStored(LAST_CHECK_KEY);
}

function writeLastCheck(value) {
  return writeStored(LAST_CHECK_KEY, value);
}

function assetValKey(url) {
  return ASSET_VAL_PREFIX + url;
}

/* Run `fn` over `items` with at most `limit` in flight at once. */
async function mapLimit(items, limit, fn) {
  let i = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (i < items.length) {
      const idx = i++;
      await fn(items[idx]);
    }
  });
  await Promise.all(workers);
}

/* HEAD every shell asset and refetch only the ones whose validator changed.
   Runs once per deploy (when the sentinel changed), never on plain reloads.
   Falls back to fetching when a validator is unavailable. */
async function refreshChangedAssets() {
  const cache = await caches.open(SHELL_CACHE);
  let failed = false;
  // Cap parallel HEAD/fetch at 6 (browser per-host limit) so the deploy refresh
  // doesn't queue dozens of requests at once.
  await mapLimit(SHELL_ASSETS, 6, async (url) => {
    const remote = await headValidator(url);
    const key = assetValKey(url);
    const stored = await readStored(key);
    /* No stored value (fresh) or a different value => refetch. */
    if (remote && stored && remote === stored) return;
    try {
      // no-store: bypass the HTTP cache AND avoid a conditional 304 (which has
      // res.ok === false and would silently keep the stale copy). Forces a 200.
      const res = await fetch(url, { cache: 'no-store' });
      if (!res || !res.ok) failed = true;
      if (res && res.ok) {
        await cache.put(url, res.clone());
        await writeStored(key, remote || validatorOf(res) || '');
      }
    } catch (err) {
      failed = true; // keep the cached copy; retried on the next check
    }
  });
  return !failed;
}

/* Record per-asset validators after a bulk precache (install time). */
async function recordAssetValidators() {
  await Promise.all(
    SHELL_ASSETS.map(async (url) => {
      const v = await headValidator(url);
      if (v) await writeStored(assetValKey(url), v);
    })
  );
}

const DEXIE_URL = 'https://unpkg.com/dexie@4.0.11/dist/modern/dexie.mjs';
const FONTS_CSS_URL =
  'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&display=swap';

/* Cache the Google Fonts stylesheet and every font file it references, so the
   app is fully offline after the first install. Must match the <link> in index.html. */
async function precacheFonts(cache) {
  const res = await fetch(FONTS_CSS_URL);
  if (!res || !res.ok) return;
  const css = await res.clone().text();
  await cache.put(FONTS_CSS_URL, res);
  const urls = Array.from(new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)'"\s]+/g) || []));
  await Promise.all(
    urls.map(async (u) => {
      try {
        const f = await fetch(u);
        if (f && f.ok) await cache.put(u, f);
      } catch (_) { }
    })
  );
}

/* ---------- Lifecycle ---------- */

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL_ASSETS.map((u) => new Request(u, { cache: 'no-cache' }))))
      .then(async () => {
        const v = await fetchSentinelValidator();
        if (v) await writeStoredValidator(v);
        await recordAssetValidators();
        // Best-effort: precache pinned Dexie + Inter fonts so the first offline boot works.
        try {
          const rc = await caches.open(RUNTIME_CACHE);
          await precacheFonts(rc).catch(() => { });
          await rc.add(DEXIE_URL);
        } catch (_) { }
      })
      .then(() => self.skipWaiting())
    // Swapping the worker changes nothing the page sees: content updates still need consent (applyUpdate).
  );
});

self.addEventListener('activate', (event) => {
  const keep = [SHELL_CACHE, RUNTIME_CACHE, META_CACHE];
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith('tokenbook-') && !keep.includes(k))
            .map((k) => caches.delete(k))
        )
      )
      .then(() => self.clients.claim())
  );
});

/* ---------- Fetch handlers ---------- */

/* On navigation: serve the cached document immediately (non-blocking first
   paint), refreshing that cache entry from the network in the background.
   Update detection is separate — see checkForUpdates(). */
async function handleNavigation(request) {
  // Navigations cached under a query/hash-stripped key so ?dev=1 and plain
  // loads share one shell entry.
  const url = new URL(request.url);
  const key = url.origin + url.pathname;
  const cached = await caches.match(key);
  if (cached) {
    // No background refresh: the shell document changes only together with its
    // assets inside refreshChangedAssets(), so HTML and JS/CSS never mismatch.
    return cached;
  }

  try {
    const fresh = await fetch(request);
    const cache = await caches.open(SHELL_CACHE);
    cache.put(key, fresh.clone());
    return fresh;
  } catch (err) {
    const fallback =
      (await caches.match('./index.html')) || (await caches.match('./'));
    if (fallback) return fallback;
    throw err;
  }
}

/* Background update check, run via event.waitUntil so it never delays the
   navigation response. Skips if the last check was under CHECK_GUARD_MS ago.
   Otherwise HEADs the version.txt sentinel; if changed, HEAD-diffs shell assets,
   refetches changed ones, then tells the requesting client to reload. */
async function checkForUpdates() {
  const lastCheck = Number(await readLastCheck()) || 0;
  if (Date.now() - lastCheck < CHECK_GUARD_MS) return;
  await writeLastCheck(String(Date.now()));

  let remote;
  try {
    remote = await fetchSentinelValidator();
  } catch (err) {
    return;
  }
  if (!remote) return;

  const stored = await readStoredValidator();
  if (stored === remote) {
    await writeStored(PENDING_KEY, '');
    return;
  }

  // Detect only: remember the new sentinel and tell every client. Nothing is
  // refetched until the user accepts the prompt (see applyUpdate).
  await writeStored(PENDING_KEY, remote);
  await notifyClients('tokenbook-update-available');
}

async function notifyClients(type) {
  const all = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  for (const c of all) c.postMessage({ type });
}

/* User accepted the prompt: refetch changed assets, then record the sentinel.
   If any asset fails the sentinel stays pending so the user can retry. */
async function applyUpdate() {
  const pending = await readStored(PENDING_KEY);
  if (!pending) return false;
  const ok = await refreshChangedAssets();
  if (!ok) {
    await notifyClients('tokenbook-update-failed');
    return false;
  }
  await writeStoredValidator(pending);
  await writeStored(PENDING_KEY, '');
  await notifyClients('tokenbook-update-applied');
  return true;
}

function isRuntimeRequest(url) {
  return RUNTIME_HOSTS.has(url.hostname);
}

/* Cross-origin runtime assets (Dexie/fonts): cache-first, best-effort. Opaque
   or CORS responses are both cached so the module is available offline. */
async function handleRuntime(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try {
    const fresh = await fetch(request);
    const cache = await caches.open(RUNTIME_CACHE);
    cache.put(request, fresh.clone());
    return fresh;
  } catch (err) {
    const cached2 = await caches.match(request);
    if (cached2) return cached2;
    throw err;
  }
}

async function handleLocal(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const fresh = await fetch(request);
  if (fresh && fresh.ok) {
    const cache = await caches.open(RUNTIME_CACHE);
    cache.put(request, fresh.clone());
  }
  return fresh;
}

self.addEventListener('message', (event) => {
  // Dev / manual-test: clear the stored sentinel + asset validators, then
  // run an update check immediately (bypassing the 30s guard).
  if (event.data && event.data.type === 'tokenbook-apply-update') {
    event.waitUntil(applyUpdate());
    return;
  }
  if (!event.data || event.data.type !== 'tokenbook-force-update') return;
  event.waitUntil(
    (async () => {
      try {
        await writeStoredValidator('');
        await writeLastCheck('0');
      } catch (_) { }
      await checkForUpdates();
    })()
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  if (request.mode === 'navigate') {
    event.respondWith(handleNavigation(request));
    event.waitUntil(checkForUpdates());
    return;
  }

  if (url.origin === self.location.origin) {
    event.respondWith(handleLocal(request));
    return;
  }
  if (isRuntimeRequest(url)) {
    event.respondWith(handleRuntime(request));
  }
});
